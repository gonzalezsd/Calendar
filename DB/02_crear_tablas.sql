CREATE TABLE usuarios (
    usuario_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255),
    apellido1 varchar(255),
    apellido2 varchar(255),
    es_administrador boolean,
    activo boolean
);

CREATE TABLE credenciales (
    usuario_id integer PRIMARY KEY REFERENCES usuarios (usuario_id),
    nombre_usuario varchar(255) NOT NULL UNIQUE,
    password_hash text NOT NULL,
    version integer NOT NULL DEFAULT 1
);

CREATE TABLE proyectos (
    proyecto_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255),
    descripcion text,
    duracion smallint CHECK (duracion <= 880),
    restantes smallint CHECK (restantes <= 880),
    laborable boolean NOT NULL DEFAULT true,
    color varchar(7) CHECK (color ~ '^#[0-9A-Fa-f]{6}$')
);

CREATE TABLE asignaciones (
    fecha date NOT NULL,
    proyecto_id integer NOT NULL REFERENCES proyectos (proyecto_id),
    es_prevision boolean NOT NULL,
    usuario_id integer NOT NULL REFERENCES usuarios (usuario_id),
    CONSTRAINT asignaciones_unicas UNIQUE (usuario_id, fecha, proyecto_id, es_prevision)
);

CREATE TABLE tipos_fecha (
    tipo_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255),
    descripcion text,
    color varchar(7) CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
    en_borde boolean
);

CREATE UNIQUE INDEX tipos_fecha_festivo_unico ON tipos_fecha (nombre)
    WHERE nombre = 'Festivo';

CREATE TABLE tipados (
    fecha date NOT NULL,
    tipo_id integer NOT NULL REFERENCES tipos_fecha (tipo_id),
    usuario_id integer NOT NULL REFERENCES usuarios (usuario_id),
    CONSTRAINT tipados_unicos UNIQUE (usuario_id, fecha, tipo_id)
);

CREATE TABLE notas (
    usuario_id integer NOT NULL REFERENCES usuarios (usuario_id),
    fecha date NOT NULL,
    texto text NOT NULL,
    PRIMARY KEY (usuario_id, fecha)
);
