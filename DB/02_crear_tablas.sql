CREATE TABLE usuarios (
    usuario_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255),
    apellido1 varchar(255),
    apellido2 varchar(255),
    es_administrador boolean
);

CREATE TABLE proyectos (
    proyecto_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255),
    descripcion text,
    duracion smallint CHECK (duracion <= 880),
    restantes smallint CHECK (restantes <= 880),
    color varchar(7) CHECK (color ~ '^#[0-9A-Fa-f]{6}$')
);

CREATE TABLE asignaciones (
    fecha date,
    proyecto_id integer REFERENCES proyectos (proyecto_id),
    es_prevision boolean
);

CREATE TABLE tipos_fecha (
    tipo_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255),
    descripcion text,
    color varchar(7) CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
    en_borde boolean
);

CREATE TABLE tipados (
    fecha date,
    tipo_id integer REFERENCES tipos_fecha (tipo_id)
);
